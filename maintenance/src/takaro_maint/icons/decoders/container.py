"""The decoder-container contract: request JSON in, a manifest and files out, no network, no writable game files.

A decoder is a small program that turns a game's own formats (Unreal packages, Unity bundles, ...) into
PNG and JSON. It lives under ``maintenance/decoders/<name>/`` with a Dockerfile, is built locally (never
pushed) and is run by image Id with every game mount read-only::

    docker run --rm --network none --read-only --tmpfs /tmp --cap-drop ALL --security-opt no-new-privileges
        --user UID:GID -v HOST:CONTAINER:ro ... -v request.json:/work/request.json:ro -v OUT:/out
        [-e NAME ...] IMAGE_ID /work/request.json

Secrets are passed by name only (``-e NAME``): the value is in the environment of the docker client and is
never in an argument list, a log line or an error message.
"""

from __future__ import annotations

import hashlib
import json
import os
import re
import shlex
import shutil
import stat
import subprocess
import tempfile
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from jsonschema import Draft202012Validator
from PIL import Image, UnidentifiedImageError

from ... import output, paths, redact
from ...exit_codes import BuildFailed, IntegrityError, UsageError
from ...paths import safe_relative
from .. import cache_entry

DECODERS_DIR = Path("maintenance") / "decoders"
CONTEXT_LABEL = "org.takaro.icons.decoder.context"
TAG_PREFIX = "takaro-icons-decoder-"
EXCLUDED_DIRECTORIES = {"bin", "obj", "__pycache__", "node_modules"}
MAX_EDGE = 4096
MAX_JSON_BYTES = 256 * 1024 * 1024
STDERR_TAIL_LINES = 40
REQUEST_ID = re.compile(r"^[a-z0-9][a-z0-9-]{0,63}$")

MANIFEST_SCHEMA: dict[str, Any] = {
    "type": "object",
    "required": ["schemaVersion", "tool", "results"],
    "additionalProperties": False,
    "properties": {
        "schemaVersion": {"const": 1},
        "tool": {"type": "object", "required": ["name", "version"]},
        "results": {
            "type": "array",
            "items": {
                "oneOf": [
                    {
                        "type": "object",
                        "required": ["id", "ok", "file", "meta"],
                        "additionalProperties": False,
                        "properties": {
                            "id": {"type": "string", "pattern": REQUEST_ID.pattern},
                            "ok": {"const": True},
                            "file": {"type": "string", "minLength": 1},
                            "meta": {"type": "object"},
                        },
                    },
                    {
                        "type": "object",
                        "required": ["id", "ok", "error", "errorKind"],
                        "additionalProperties": False,
                        "properties": {
                            "id": {"type": "string", "pattern": REQUEST_ID.pattern},
                            "ok": {"const": False},
                            "error": {"type": "string"},
                            "errorKind": {"enum": ["unsupported-format", "not-found", "failed"]},
                        },
                    },
                ]
            },
        },
    },
}
_MANIFEST_VALIDATOR = Draft202012Validator(MANIFEST_SCHEMA)


@dataclass(frozen=True)
class DecoderImage:
    name: str
    id: str
    context_sha256: str
    tag: str


@dataclass(frozen=True)
class Mount:
    host: Path
    container: str
    read_only: bool = True


@dataclass(frozen=True)
class Manifest:
    """A validated decoder answer: where its files are and what each export produced."""

    root: Path
    tool: dict[str, Any]
    results: dict[str, dict[str, Any]]

    def file(self, export_id: str) -> Path:
        return self.root / str(self.results[export_id]["file"])

    def failures(self) -> list[dict[str, Any]]:
        return [result for result in self.results.values() if not result["ok"]]


def docker_argv() -> list[str]:
    """The docker CLI: ``TAKARO_MAINT_ICONS_DECODER`` (a test double), else ``TAKARO_MAINT_DOCKER``, else ``docker``."""
    override = os.environ.get("TAKARO_MAINT_ICONS_DECODER") or os.environ.get("TAKARO_MAINT_DOCKER") or "docker"
    return shlex.split(override)


def require_docker() -> list[str]:
    argv = docker_argv()
    if shutil.which(argv[0]) is None and not Path(argv[0]).is_file():
        raise UsageError(
            f"docker is required for games whose icons are decoded or generated by a decoder container, but "
            f"{argv[0]!r} "
            "was not found (set TAKARO_MAINT_DOCKER to another docker CLI)",
            docker=argv[0],
        )
    return argv


def decoder_dir(name: str) -> Path:
    return paths.repo_root() / DECODERS_DIR / name


def context_sha256(name: str) -> str:
    """sha256 over the sorted ``<relative path>\\t<sha256>\\n`` lines of every source file of the decoder."""
    root = decoder_dir(name)
    if not root.is_dir():
        raise UsageError(f"no decoder named {name!r} under {root.parent}")
    lines = []
    for path in sorted(root.rglob("*")):
        relative = path.relative_to(root)
        if path.is_file() and not EXCLUDED_DIRECTORIES.intersection(relative.parts):
            lines.append(f"{relative.as_posix()}\t{hashlib.sha256(path.read_bytes()).hexdigest()}\n")
    return hashlib.sha256("".join(lines).encode("utf-8")).hexdigest()


def tag_for(name: str, context: str) -> str:
    return f"{TAG_PREFIX}{name}:{context[:16]}"


def _inspect(docker: Sequence[str], tag: str) -> dict[str, Any] | None:
    completed = subprocess.run([*docker, "image", "inspect", tag], capture_output=True, text=True, check=False)
    if completed.returncode != 0:
        return None
    entries = json.loads(completed.stdout)
    return entries[0] if entries else None


def inspect_state(name: str) -> dict[str, Any]:
    """The pinned image's state without building it, for ``icons inputs`` (``None`` without docker)."""
    context = context_sha256(name)
    tag = tag_for(name, context)
    argv = docker_argv()
    if shutil.which(argv[0]) is None and not Path(argv[0]).is_file():
        return {"name": name, "context": context, "tag": tag, "imageBuilt": None}
    found = _inspect(argv, tag)
    built = found is not None and (found.get("Config", {}).get("Labels") or {}).get(CONTEXT_LABEL) == context
    return {"name": name, "context": context, "tag": tag, "imageBuilt": built}


def ensure_image(name: str) -> DecoderImage:
    """The decoder image for the current sources, built locally when it is missing or stale.

    The network is used by ``docker build`` (the NuGet restore) and by nothing that runs afterwards.
    """
    docker = require_docker()
    context = context_sha256(name)
    tag = tag_for(name, context)
    found = _inspect(docker, tag)
    if found is None or (found.get("Config", {}).get("Labels") or {}).get(CONTEXT_LABEL) != context:
        output.info(f"building decoder image {tag} (the network is used for the build only)")
        completed = subprocess.run(
            [*docker, "build", "--label", f"{CONTEXT_LABEL}={context}", "-t", tag, str(decoder_dir(name))],
            capture_output=True,
            text=True,
            check=False,
        )
        if completed.returncode != 0:
            raise BuildFailed(
                f"docker build of {tag} failed",
                tail=_tail(completed.stderr + completed.stdout),
            )
        found = _inspect(docker, tag)
    if found is None or (found.get("Config", {}).get("Labels") or {}).get(CONTEXT_LABEL) != context:
        raise BuildFailed(f"image {tag} does not carry the decoder context label {context}")
    return DecoderImage(name=name, id=str(found["Id"]), context_sha256=context, tag=tag)


def _tail(text: str, extra: list[str] | None = None) -> list[str]:
    lines = redact.redact(text, extra).splitlines()
    return lines[-STDERR_TAIL_LINES:]


def run_argv(
    docker: Sequence[str], image: DecoderImage, request_file: Path, mounts: list[Mount], out: Path, env_names: list[str]
) -> list[str]:
    argv = [
        *docker,
        "run",
        "--rm",
        "--network",
        "none",
        "--read-only",
        "--tmpfs",
        "/tmp",
        "--cap-drop",
        "ALL",
        "--security-opt",
        "no-new-privileges",
        "--user",
        f"{os.getuid()}:{os.getgid()}",
    ]
    for mount in mounts:
        argv += ["-v", f"{mount.host}:{mount.container}{':ro' if mount.read_only else ''}"]
    argv += ["-v", f"{request_file}:/work/request.json:ro", "-v", f"{out}:/out"]
    for name in env_names:
        argv += ["-e", name]
    return [*argv, image.id, "/work/request.json"]


def run(
    image: DecoderImage,
    request: dict[str, Any],
    mounts: list[Mount],
    out: Path,
    env_names: list[str] | None = None,
) -> Manifest:
    """Run the decoder once and return its validated manifest. ``out`` must be an empty directory."""
    names = env_names or []
    _validate_request(request)
    docker = require_docker()
    out.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="decoder-request-") as scratch:
        request_file = Path(scratch) / "request.json"
        request_file.write_text(json.dumps(request, indent=2) + "\n", encoding="utf-8")
        argv = run_argv(docker, image, request_file, mounts, out, names)
        completed = subprocess.run(argv, capture_output=True, text=True, check=False)
    extra = [os.environ[name] for name in names if os.environ.get(name)]
    if completed.returncode != 0:
        raise BuildFailed(
            f"the {image.name} decoder exited {completed.returncode}",
            exit=completed.returncode,
            stderr=_tail(completed.stderr, extra),
        )
    return read_manifest(out, [str(export["id"]) for export in request["exports"]])


def _validate_request(request: dict[str, Any]) -> None:
    ids = [str(export.get("id")) for export in request.get("exports", [])]
    bad = [export_id for export_id in ids if not REQUEST_ID.fullmatch(export_id)]
    if bad or len(set(ids)) != len(ids):
        raise UsageError("decoder export ids must be unique and match " + REQUEST_ID.pattern, ids=bad[:20])


def check_tree(root: Path) -> None:
    """Refuse an output tree holding anything but plain files and directories.

    ``/out`` is writable by the decoder, which reads attacker-controlled game files. A symlink or a hardlinked
    file planted there would make this tool follow it outside the tree when it hashes, reads or marks the output.
    Nothing is followed: every entry is examined with ``lstat``.
    """
    pending = [root]
    while pending:
        with os.scandir(pending.pop()) as entries:
            for entry in entries:
                info = entry.stat(follow_symlinks=False)
                if stat.S_ISLNK(info.st_mode):
                    raise BuildFailed(f"the decoder output holds a symlink: {entry.path}", path=entry.path)
                if stat.S_ISDIR(info.st_mode):
                    pending.append(Path(entry.path))
                elif not stat.S_ISREG(info.st_mode):
                    raise BuildFailed(f"the decoder output holds a special file: {entry.path}", path=entry.path)
                elif info.st_nlink > 1:
                    raise BuildFailed(f"the decoder output holds a hardlinked file: {entry.path}", path=entry.path)


def read_manifest(out: Path, expected_ids: list[str]) -> Manifest:
    """The manifest under ``out``, checked against the contract; any violation is a failed build."""
    check_tree(out)
    manifest_path = out / "manifest.json"
    if not manifest_path.is_file():
        raise BuildFailed("the decoder wrote no manifest.json")
    try:
        document = json.loads(manifest_path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise BuildFailed(f"the decoder manifest is not valid JSON: {exc}") from exc
    errors = sorted(_MANIFEST_VALIDATOR.iter_errors(document), key=lambda error: list(error.absolute_path))
    if errors:
        raise BuildFailed(
            "the decoder manifest violates the contract",
            problems=[
                f"{'/'.join(str(part) for part in e.absolute_path) or '<root>'}: {e.message}" for e in errors[:20]
            ],
        )
    results: dict[str, dict[str, Any]] = {}
    for result in document["results"]:
        if result["id"] in results:
            raise BuildFailed(f"the decoder manifest lists export {result['id']!r} twice")
        results[result["id"]] = result
    missing = sorted(set(expected_ids) - set(results))
    extra = sorted(set(results) - set(expected_ids))
    if missing or extra:
        raise BuildFailed(
            "the decoder manifest does not answer exactly the requested exports",
            missing=missing[:20],
            unrequested=extra[:20],
        )
    for result in results.values():
        if result["ok"]:
            _check_file(out, result)
    return Manifest(root=out, tool=document["tool"], results=results)


def _check_file(out: Path, result: dict[str, Any]) -> None:
    relative = result["file"]
    try:
        safe_relative(relative, field=f"decoder file for {result['id']}")
    except UsageError as exc:
        raise BuildFailed(str(exc), export=result["id"]) from exc
    path = out / relative
    if not path.resolve().is_relative_to(out.resolve()):
        raise BuildFailed(f"{relative} resolves outside the decoder output", export=result["id"])
    if not path.is_file():
        raise BuildFailed(f"the decoder manifest names {relative} for {result['id']} but it was not written")
    if relative.endswith(".png"):
        try:
            with Image.open(path, formats=["PNG"]) as image:
                width, height = image.size
        except (UnidentifiedImageError, OSError) as exc:
            raise BuildFailed(f"{relative} is not a PNG ({exc})", export=result["id"]) from exc
        if not (0 < width <= MAX_EDGE and 0 < height <= MAX_EDGE):
            raise BuildFailed(f"{relative} is {width}x{height}, outside 1..{MAX_EDGE}", export=result["id"])
    elif path.stat().st_size > MAX_JSON_BYTES:
        raise BuildFailed(f"{relative} is larger than {MAX_JSON_BYTES} bytes", export=result["id"])


def _canonical(value: Any) -> str:
    return json.dumps(value, sort_keys=True, separators=(",", ":"))


def decode_key(image: DecoderImage, request: dict[str, Any], inputs_sha256: str, secrets_sha256: str = "") -> str:
    parts = (image.id, _canonical(request), inputs_sha256, *([secrets_sha256] if secrets_sha256 else []))
    return hashlib.sha256("\n".join(parts).encode("utf-8")).hexdigest()


def _secrets_sha256(env_names: list[str] | None) -> str:
    if not env_names:
        return ""
    values = "\n".join(f"{name}={os.environ.get(name, '')}" for name in sorted(env_names))
    return hashlib.sha256(values.encode("utf-8")).hexdigest()


def _output_hashes(root: Path) -> dict[str, str]:
    return {
        path.relative_to(root).as_posix(): hashlib.sha256(path.read_bytes()).hexdigest()
        for path in sorted(root.rglob("*"))
        if path.is_file() and path.relative_to(root) != cache_entry.MARKER
    }


def run_cached(
    image: DecoderImage,
    request: dict[str, Any],
    mounts: list[Mount],
    *,
    inputs_sha256: str,
    cache: Path,
    env_names: list[str] | None = None,
) -> Manifest:
    """``run`` through the decode cache: the same image, request and input tree decode once.

    A hit is re-hashed against the marker; a mismatch decodes again once. The decoded files stay in the cache.
    An entry holding a ``failed`` result is decoded again rather than reused. The values of the secret variables
    are part of the key (as a digest) and are never stored or logged.
    """
    key = decode_key(image, request, inputs_sha256, _secrets_sha256(env_names))
    directory = cache / "icons" / "decoded" / key
    expected_ids = [str(export["id"]) for export in request["exports"]]
    marker = cache_entry.read_marker(directory, "files")
    if marker is not None:
        check_tree(directory)
        if _output_hashes(directory) == marker["files"]:
            manifest = read_manifest(directory, expected_ids)
            if not any(result["errorKind"] == "failed" for result in manifest.failures()):
                output.info(f"decoded outputs {key[:12]} are already in the decode cache")
                return manifest
            output.info(f"decode cache {key[:12]} holds failed exports; decoding again")
        else:
            output.warn(f"corrupt decode cache {key[:12]}; decoding again once")
    elif directory.exists():
        output.warn(f"corrupt decode cache {key[:12]}; decoding again once")

    def decode(staging: Path) -> dict[str, Any]:
        run(image, request, mounts, staging, env_names)
        return {"image": image.id, "files": _output_hashes(staging)}

    marker = cache_entry.store(directory, decode)
    if _output_hashes(directory) != marker["files"]:
        raise IntegrityError(f"the decode cache {key[:12]} does not match its own marker after a fresh decode")
    return read_manifest(directory, expected_ids)
