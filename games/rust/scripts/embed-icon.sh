#!/usr/bin/env bash
# Writes assets/icon-256.png into mod/TakaroConnector.cs as the base64 constant between
# `takaro:icon-begin` and `takaro:icon-end`. The plugin ships as that one .cs file, so the
# icon travels inside it; the revision and size Takaro sees are computed from these bytes
# when the plugin loads. tests/protocol/run.sh fails when the two differ.
#
# Usage: embed-icon.sh [--check]
set -euo pipefail

SCRIPT_DIR=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
PROJECT_ROOT=$(cd -- "${SCRIPT_DIR}/.." && pwd)
SOURCE="${PROJECT_ROOT}/mod/TakaroConnector.cs"
ICON="${PROJECT_ROOT}/assets/icon-256.png"

if ! grep -q '// takaro:icon-begin' "${SOURCE}" || ! grep -q '// takaro:icon-end' "${SOURCE}"; then
    echo "error: the icon region markers are missing from ${SOURCE}" >&2
    exit 5
fi

TMP=$(mktemp)
trap 'rm -f "${TMP}" "${TMP}.region"' EXIT
{
    echo '        // takaro:icon-begin'
    echo '        // Generated by scripts/embed-icon.sh from assets/icon-256.png; do not edit by hand.'
    echo '        internal const string GameIconBase64 = @"'
    base64 -w 100 "${ICON}"
    echo '";'
    echo '        // takaro:icon-end'
} > "${TMP}.region"

awk -v region="${TMP}.region" '
    /\/\/ takaro:icon-begin/ { while ((getline line < region) > 0) print line; skip = 1; next }
    /\/\/ takaro:icon-end/ { skip = 0; next }
    !skip { print }
' "${SOURCE}" > "${TMP}"

if [ "${1:-}" = "--check" ]; then
    cmp -s "${TMP}" "${SOURCE}" || { echo "mod/TakaroConnector.cs does not embed assets/icon-256.png; run scripts/embed-icon.sh" >&2; exit 1; }
    echo "the embedded icon matches assets/icon-256.png"
    exit 0
fi
cat "${TMP}" > "${SOURCE}"
echo "embedded $(wc -c < "${ICON}") bytes of assets/icon-256.png"
