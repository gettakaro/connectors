#!/usr/bin/env node
// Embeds games/dune/assets/icon-256.png into the sidecar as src/takaro/gameIcon.generated.ts, so every build (tsc,
// Dockerfile.dev with the sidecar as its context, the release tarball) carries the icon. Run after changing the PNG;
// a unit test fails while the two differ.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const png = path.resolve(here, '..', '..', 'assets', 'icon-256.png');
const out = path.resolve(here, '..', 'src', 'takaro', 'gameIcon.generated.ts');

const base64 = fs.readFileSync(png).toString('base64');
const lines = base64.match(/.{1,100}/g) ?? [];
fs.writeFileSync(
  out,
  [
    '// Generated by scripts/gen-game-icon.mjs from games/dune/assets/icon-256.png. Do not edit.',
    'export const GAME_ICON_PNG_BASE64 = [',
    ...lines.map((l) => `  '${l}',`),
    "].join('');",
    '',
  ].join('\n'),
);
console.log(`${path.relative(process.cwd(), out)}: ${Buffer.byteLength(base64, 'base64')} bytes`);
