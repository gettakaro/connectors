#!/usr/bin/env python3
"""Generate src/locationlabels.cpp: the English map name of every location listLocations answers with.

The dedicated server ships no localisation. The game client names a map marker through its
LocaTagComponent: 8kMapLabel_steppes_areaName_02_TwinPeaks is "Pillars of Creation" on the in-game
map, 8kMapLabel_grassland_town_10_SalineSprings is "Saline Springs". Those En_Us names come from the
same client export as the item and entity labels (templates-en.tsv: template guid, code, En_Us
name, naming component; see gen_item_labels.py).

Only places a player can find on the in-game map are kept:
  - a marker the client names, unless its code says the game hides it (`noUI`: quest search areas
    and placeholders that never show an icon);
  - a fast travel platform (Teleport_Platform_*), which the client draws as a Fast Travel Point
    but does not name.
Everything else (respawn save points, boss braziers, the spire beacons that sit on top of an
already-named Ancient Spire, trigger zones) is left out: it has no name a player would recognise.

    gen_location_labels.py <templates-en.tsv> <locations.json> [build note]

locations.json is the server placement table gen_gamedata.py bakes into gamedata.cpp.
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.normpath(os.path.join(HERE, '..', 'src', 'locationlabels.cpp'))

# Unnamed in the client but drawn on its map. The name is the game's own term (En_Us "Fast Travel
# Point Unlocked!").
UNNAMED = [(re.compile(r'^Teleport_Platform_'), 'Fast Travel Point')]


def c(s):
    return json.dumps(s, ensure_ascii=True)


def clean(name):
    """The client's markup (<location>, <npc>, ...) is styling, not text."""
    return ' '.join(re.sub(r'</?[A-Za-z]+>', '', name).split())


def label(code, en):
    if 'noui' in code.lower():
        return None
    if en:
        return en
    for rx, name in UNNAMED:
        if rx.search(code):
            return name
    return None


def main():
    tsv, locs_path = sys.argv[1], sys.argv[2]
    note = sys.argv[3] if len(sys.argv) > 3 else ''
    names = {}
    for line in open(tsv, encoding='utf-8'):
        f = line.rstrip('\n').split('\t')
        if len(f) >= 3 and f[0]:
            names[f[0]] = clean(f[2])
    by_code = {}
    for loc in json.load(open(locs_path))['locations']:
        name = label(loc['code'], names.get(loc['templateGuid'], ''))
        if name is None:
            continue
        old = by_code.setdefault(loc['code'], name)
        if old != name:
            sys.exit(f"{loc['code']}: two names, {old!r} and {name!r}")
    o = ['// GENERATED by tools/gen_location_labels.py - do not edit.', '#include "location.h"', '',
         '// source: game client En_Us localisation' + (', ' + note if note else ''),
         'const LocationLabel kLocationLabels[] = {']
    o += ['  {%s,%s},' % (c(k), c(by_code[k])) for k in sorted(by_code, key=lambda s: s.encode())]
    o += ['};', 'const size_t kLocationLabelCount = sizeof(kLocationLabels) / sizeof(kLocationLabels[0]);', '']
    open(OUT, 'w').write('\n'.join(o))
    print('wrote', OUT, len(by_code), 'codes')


if __name__ == '__main__':
    main()
