#!/usr/bin/env python3
"""Writes src/game_icon_png.inc, the Game Profile icon compiled into libtakaro-vein.so.

The icon is games/vein/assets/icon-256.png (256 x 256 PNG, at most 128 KiB). The plugin computes
its revision (sha256) and size from these bytes at startup, so a changed icon always declares a new
revision. Run this after replacing the PNG; tests/run.sh fails when the two differ.

  gen_game_icon.py           # regenerate
  gen_game_icon.py --check   # exit 1 when the .inc does not match the PNG
"""
import argparse
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PNG = ROOT.parent / 'assets' / 'icon-256.png'
INC = ROOT / 'src' / 'game_icon_png.inc'
MAX_BYTES = 128 * 1024


def render(png: bytes) -> str:
    if png[:8] != b'\x89PNG\r\n\x1a\n' or png[12:16] != b'IHDR':
        sys.exit(f'{PNG} is not a PNG')
    width, height = struct.unpack('>II', png[16:24])
    if (width, height) != (256, 256):
        sys.exit(f'{PNG} is {width}x{height}, Takaro needs 256x256')
    if len(png) > MAX_BYTES:
        sys.exit(f'{PNG} is {len(png)} bytes, Takaro takes at most {MAX_BYTES}')
    lines = ['// Generated by tools/gen_game_icon.py from games/vein/assets/icon-256.png. Do not edit.']
    for i in range(0, len(png), 24):
        lines.append(','.join(str(b) for b in png[i:i + 24]) + ',')
    return '\n'.join(lines) + '\n'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()
    text = render(PNG.read_bytes())
    if a.check:
        if not INC.exists() or INC.read_text() != text:
            print(f'{INC.relative_to(ROOT)} does not match {PNG.name}: run tools/gen_game_icon.py', file=sys.stderr)
            sys.exit(1)
        return
    INC.write_text(text)
    print(f'wrote {INC.relative_to(ROOT)} ({PNG.stat().st_size} bytes of PNG)')


if __name__ == '__main__':
    main()
