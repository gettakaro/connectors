// Writes src/generated/buildInfo.ts from the files release-please and the repo own:
// the connector version from games/terraria/version.txt and the Game Profile icon from
// games/terraria/assets/icon-256.png. Runs before build, test and dev, so the version
// Takaro sees is always the release version and never a hand-written literal.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const bridgeDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const gameDir = path.resolve(bridgeDir, '..');

// Semver 2.0.0, build metadata allowed (https://semver.org/#is-there-a-suggested-regular-expression-regex-to-check-a-semver-string).
const SEMVER = /^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)(?:-((?:0|[1-9]\d*|\d*[a-zA-Z-][0-9a-zA-Z-]*)(?:\.(?:0|[1-9]\d*|\d*[a-zA-Z-][0-9a-zA-Z-]*))*))?(?:\+([0-9a-zA-Z-]+(?:\.[0-9a-zA-Z-]+)*))?$/;

const version = readFileSync(path.join(gameDir, 'version.txt'), 'utf8').trim();
if (!SEMVER.test(version) || version.length > 64) {
  throw new Error(`games/terraria/version.txt is not strict semver: ${JSON.stringify(version)}`);
}
const icon = readFileSync(path.join(gameDir, 'assets', 'icon-256.png'));

const out = path.join(bridgeDir, 'src', 'generated', 'buildInfo.ts');
mkdirSync(path.dirname(out), { recursive: true });
writeFileSync(out, [
  '// Generated by scripts/generate-build-info.mjs; do not edit.',
  `export const CONNECTOR_VERSION = ${JSON.stringify(version)};`,
  `export const GAME_ICON_PNG_BASE64 = ${JSON.stringify(icon.toString('base64'))};`,
  '',
].join('\n'));
