-- Config parsing, defaults, template creation, identity token, and no token in any log line.
local t = require("lib.t")
local F = require("lib.fakes")
local config = require("takaro.config")

t.test("parse: comments, spacing, case of keys, CRLF, unknown keys reported", function()
  local raw, unknown = config.parse("# c\r\n takaro_ws_url = wss://x/ \r\nFOO=bar\n;x\nSERVER_NAME=A=B\n")
  t.eq(raw.TAKARO_WS_URL, "wss://x/")
  t.eq(raw.SERVER_NAME, "A=B")
  t.deep(unknown, { "FOO" })
end)

t.test("defaults: takaro.io URL, destructive off, empty allowlist, frame logging off", function()
  local c = config.build({})
  t.eq(c.url, "wss://connect.takaro.io/")
  t.eq(c.destructive, false)
  t.deep(c.allowlist, {})
  t.eq(c.logFrames, false)
end)

t.test("allowlist: comma/space separated, case-insensitive, leading # ignored", function()
  t.deep(config.allowlist_set("#Announce, listplayers  Teleport"), { announce = true, listplayers = true, teleport = true })
end)

t.test("a missing config file is created from the template and the connector stays idle", function()
  local App = require("takaro.app")
  local native = F.native()
  local fs = F.fs({})
  local app = App.new({ native = native, mod_dir = "/mod", fs = fs, game = F.game() })
  app:start()
  t.ok(fs.files["/mod/TakaroConfig.txt"]:find("REGISTRATION_TOKEN=", 1, true))
  t.eq(native.connected, nil, "no connect without a registration token")
  t.ok(fs.files["/mod/TakaroIdentity.txt"]:match("^scum%-%x+"), "identity generated")
end)

t.test("a generated identity token is reused on the next start", function()
  local App = require("takaro.app")
  local fs = F.fs({ ["/mod/TakaroConfig.txt"] = "REGISTRATION_TOKEN=abcdefgh\n", ["/mod/TakaroIdentity.txt"] = "scum-keepme\n" })
  local native = F.native()
  local app = App.new({ native = native, mod_dir = "/mod", fs = fs, game = F.game() })
  app:start()
  local tk = F.takaro(app, native)
  tk.connect()
  t.eq(native.frames("identify")[1].msg.payload.identityToken, "scum-keepme")
end)

t.test("token values never appear in any log line, even with LOG_FRAMES=true", function()
  local app, native, tk = F.app({ extra = "LOG_FRAMES=true" })
  tk.connect()
  tk.request("getPlayers", {})
  native.deliver({ type = "identifyResponse", payload = { error = { message = "bad token " .. F.REG_TOKEN } } })
  tk.pump()
  app:log_status()
  local all = table.concat(native.logs, "\n")
  t.ok(#native.logs > 5, "frames were logged")
  t.ok(all:find('"type":"identify"', 1, true), "identify frame logged (redacted)")
  t.eq(all:find(F.REG_TOKEN, 1, true), nil, "registration token leaked")
  t.eq(all:find(F.ID_TOKEN, 1, true), nil, "identity token leaked")
end)

t.test("describe() reports token presence only", function()
  local c = config.build(config.parse(F.config_text()))
  local d = config.describe(c)
  t.eq(d:find(F.REG_TOKEN, 1, true), nil)
  t.ok(d:find("registrationToken=set", 1, true))
end)

t.test("known players persist to known-players.json and load on start", function()
  local game = F.game({ list_players = { ok = true, value = { { steamId = "76561198000000001", name = "Alice" } } } })
  local app, native, tk, _, fs = F.app({ game = game })
  tk.connect()
  tk.request("getPlayers", {})
  tk.pump()
  native.clock = native.clock + 31000
  tk.pump()
  t.ok(fs.files["/mod/known-players.json"]:find("Alice", 1, true))
  local App = require("takaro.app")
  local app2 = App.new({ native = F.native(), mod_dir = "/mod", fs = fs, game = F.game() })
  app2:start()
  t.eq(app2.known:resolve("76561198000000001").name, "Alice")
end)

t.test("TakaroConfig.txt.example equals the template the connector writes", function()
  local f = assert(io.open("TakaroConfig.txt.example", "rb"))
  local s = f:read("a")
  f:close()
  t.eq(s, config.TEMPLATE)
end)

t.run("config")
